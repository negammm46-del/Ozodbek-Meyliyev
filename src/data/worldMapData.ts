export function getCountryFactByAtlasName(atlasName: string): MapCountryFact {
  const coreId = CORE_COUNTRY_MAP[atlasName];
  if (coreId) {
    const core = COUNTRIES.find((c) => c.id === coreId);
    if (core) {
      return {
        atlasName,
        uzbekName: core.name,
        continent: ATLAS_NAME_TO_CONTINENT[atlasName] ?? 'Osiyo',
        capital: core.capital,
        areaKm2: core.areaKm2,
        population: core.populationM,
        coordinates: core.coordinates,
        shortNote: core.shortNote,
        funFact: core.funFact,
        isFeatured: true,
      };
    }
  }

  if (EXTRA_COUNTRY_FACTS[atlasName]) {
    return EXTRA_COUNTRY_FACTS[atlasName];
  }

  const continent = ATLAS_NAME_TO_CONTINENT[atlasName] ?? 'Osiyo';
  const continentInfo = CONTINENT_FACTS[continent];
  const uzbekName = UZBEK_COUNTRY_NAMES[atlasName] ?? atlasName;

  return {
    atlasName,
    uzbekName,
    continent,
    shortNote: `${uzbekName} — ${continent} qit’asida joylashgan hudud. ${continentInfo.teacherSummary}`,
    funFact: continentInfo.funFact,
    isFeatured: false,
  };
}

